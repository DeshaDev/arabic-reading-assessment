// دالة مساعدة لحساب التوزيع الفراغي لكلمات النص
function tokenizeAndBoundWords(text, containerWidth, containerHeight, fontSize = 28, lineHeight = 2.4) {
  const lines = text.trim().split('\n');
  const wordsMap = [];
  const lineSpacingPx = fontSize * lineHeight;
  let currentY = 40; // Top margin

  lines.forEach((lineText, lineIdx) => {
    const words = lineText.trim().split(/\s+/);
    // RTL layout: right to left
    let currentX = containerWidth - 30; // Start from right margin

    words.forEach((word, wordIdx) => {
      // Rough estimation of word width based on Arabic character count
      // Clean word from tashkeel to calculate actual visual glyph width
      const cleanWord = word.replace(/[\u064B-\u065F\u0670]/g, '');
      const wordWidth = Math.max(35, cleanWord.length * (fontSize * 0.58));
      
      const box = {
        id: `w_${lineIdx}_${wordIdx}`,
        word: word,
        cleanWord: cleanWord,
        lineIndex: lineIdx,
        wordIndex: wordIdx,
        // Bounding box with safety margins for diacritics
        x1: currentX - wordWidth,
        y1: currentY - 8,
        x2: currentX,
        y2: currentY + fontSize + 16,
        centerX: currentX - (wordWidth / 2),
        centerY: currentY + (fontSize / 2)
      };

      wordsMap.push(box);
      currentX -= (wordWidth + 16); // Word spacing
    });

    currentY += lineSpacingPx;
  });

  return {
    words: wordsMap,
    totalLines: lines.length,
    renderedHeight: currentY + 40
  };
}

